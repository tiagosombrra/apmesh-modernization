ROOT = Path(__file__).parent
CASES = ROOT / "fixtures" / "cases"
HISTORY = ROOT / "fixtures" / "experiments" / "synthetic_nonmonotone_epochs.csv"
REAL_P1 = ROOT / "fixtures" / "real_p1" / "accepted.obj"
FIG_W_MM, FIG_H_MM = 182, 112
FIG_STYLE = {
    "font.family": "DejaVu Sans", "font.size": 7, "pdf.fonttype": 42,
    "svg.fonttype": "path", "svg.hashsalt": "APMeshMeshStudioS5bSynthetic",
    "axes.unicode_minus": False,
    "axes.edgecolor": "#536778", "savefig.facecolor": "white",
}
FIXTURES = (
    ("TRI", "synthetic_planar_tri_grid.obj"),
    ("QUAD/TRI", "synthetic_quad_aft_transition.obj"),
    ("All-QUAD", "synthetic_planar_quad_grid.obj"),
)


def _sha(path: Path) -> str:
    return sha256(path.read_bytes()).hexdigest()


def _json(path: Path, data: dict) -> None:
    path.write_text(json.dumps(data, sort_keys=True, indent=2,
                               allow_nan=False, ensure_ascii=True) + "\n",
                    encoding="utf-8", newline="\n")


def _render_pair(fig, prefix: Path) -> None:
    """Export two true-vector variants with metadata chosen for repeatability."""
    from matplotlib.backends.backend_pdf import FigureCanvasPdf
    from matplotlib.backends.backend_svg import FigureCanvasSVG
    FigureCanvasSVG(fig).print_svg(str(prefix.with_suffix('.svg')),
                                   metadata={"Date": None, "Creator": "APMesh Mesh Studio S5b"})
    FigureCanvasPdf(fig).print_pdf(str(prefix.with_suffix('.pdf')),
                                   metadata={"CreationDate": None, "ModDate": None,
                                             "Creator": "APMesh Mesh Studio S5b"})
    fig.clear()


def _topology_gallery(documents: list, target: Path) -> None:
    from matplotlib.figure import Figure
    from matplotlib.patches import Polygon
    import matplotlib as mpl
    with mpl.rc_context(FIG_STYLE):
        fig = Figure(figsize=(FIG_W_MM / 25.4, FIG_H_MM / 25.4), dpi=150,
                     facecolor='white')
        fig.text(.05, .945, "Mesh topology examples  |  synthetic fixtures only",
                 fontsize=12, fontweight='bold', color='#193349')
        fig.text(.05, .897,
                 "Independent pedagogical examples; different resolutions and mesh generation policies",
                 fontsize=7, color='#445D70')
        for i, (doc, (label, filename)) in enumerate(zip(documents, FIXTURES)):
            left = .041 + i * .315
            ax = fig.add_axes([left + .014, .29, .276, .49])
            ax.set_title(f"({chr(97+i)})  {label}", loc='left', fontsize=9,
                         fontweight='bold', pad=8, color='#173349')
            ax.set_aspect('equal')
            # Each panel is explicitly separately fitted: not a comparable physical camera.
            xs = [p[0] for p in doc.points]
            ys = [p[1] for p in doc.points]
            w, h = max(xs) - min(xs), max(ys) - min(ys)
            size = max(w, h) * .08
            ax.set_xlim(min(xs) - size, max(xs) + size)
            ax.set_ylim(min(ys) - size, max(ys) + size)
            ax.set_xticks([])
            ax.set_yticks([])
            ax.set_facecolor('#FBFCFD')
            for face in doc.faces:
                xy = [(doc.points[k][0], doc.points[k][1]) for k in face.vertices]
                ax.add_patch(Polygon(xy, closed=True,
                                     facecolor='#B2DEE0' if face.element_type == 'quad'
                                     else '#DAE1E8', edgecolor='#273E52', lw=.7))
            ax.text(.0, -.14, f"{doc.triangles} TRI  /  {doc.quads} QUAD",
                    transform=ax.transAxes, ha='left', fontsize=8,
                    fontweight='bold', color='#263B4F')
            ax.text(.0, -.22, filename, transform=ax.transAxes,
                    ha='left', fontsize=5.3, color='#516577')
        fig.text(.05, .145,
                 "SYNTHETIC - NOT measured APMesh algorithm results - NOT a fair method benchmark",
                 fontsize=8, color='#9B3743', weight='bold')
        fig.text(.05, .092,
                 "Panels have separate model coordinates and plot extents. Counts/shape scores are not performance claims.",
                 fontsize=6.8, color='#4A6273')
        _render_pair(fig, target)


def _synthetic_timeline(events: tuple, target: Path) -> None:
    from matplotlib.figure import Figure
    import matplotlib as mpl
    with mpl.rc_context(FIG_STYLE):
        fig = Figure(figsize=(FIG_W_MM / 25.4, FIG_H_MM / 25.4), dpi=150,
                     facecolor='white')
        fig.text(.05, .955, "Mock experiment histories  |  accepted vs rejected",
                 fontsize=11.5, fontweight='bold', color='#193349')
        fig.text(.05, .907, "Invented input CSV: not actual TRI/QUAD runs, error or timings",
                 fontsize=7.2, color='#8B3741')
        methods = sorted({e.method for e in events})
        colors = {'tri': '#2E617C', 'hybrid': '#368782', 'all_quad': '#7A648C'}
        axes = [fig.add_axes([.075,.36,.39,.42]), fig.add_axes([.57,.36,.355,.42])]
        for i, ax in enumerate(axes):
            for method in methods:
                rows = sorted((e for e in events if e.method == method), key=lambda e: e.epoch)
                accepted = [r for r in rows if r.accepted]
                rejected = [r for r in rows if not r.accepted]
                x = (lambda r: r.elements) if i == 0 else (lambda r: r.epoch)
                y = (lambda r: r.normalized_error) if i == 0 else (lambda r: r.wall_seconds)
                ax.plot([x(r) for r in accepted], [y(r) for r in accepted],
                        marker='o', markersize=4, lw=1.6, color=colors[method],
                        label=f'{method.upper()} accepted')
                if rejected:
                    ax.scatter([x(r) for r in rejected], [y(r) for r in rejected],
                               marker='x', s=47, lw=1.9, color=colors[method],
                               label=f'{method.upper()} rejected')
            ax.set_ylabel('Normalized error (invented)' if i == 0 else 'Wall seconds (invented)', fontsize=7)
            ax.set_xlabel('Element count (invented)' if i == 0 else 'Attempted epoch',fontsize=7)
            ax.set_title('(a) Error vs elements' if i == 0 else '(b) Attempted epoch vs time',
                         fontsize=8,loc='left',fontweight='bold',pad=9,color='#193349')
            ax.tick_params(labelsize=6)
            ax.spines['top'].set_visible(False)
            ax.spines['right'].set_visible(False)
            ax.grid(alpha=.2, lw=.4)
        handles, labels = axes[0].get_legend_handles_labels()
        fig.legend(handles, labels, ncol=2, bbox_to_anchor=(.5, .215), loc='center',
                   fontsize=6.6, frameon=False)
        fig.text(.05, .13,
                 'Lines connect ACCEPTED states only. Rejected candidates are crosses and never part of the accepted curve.',
                 fontsize=7.2, color='#304D61')
        fig.text(.05, .07,
                 'SYNTHETIC - no source-model SHA or common scientific metric: numerical method comparison is prohibited.',
                 fontsize=7, color='#9B3743', fontweight='bold')
        _render_pair(fig, target)


def export_synthetic_comparison_bundle(output_dir: Path | str, *,
                                       fixture_dir: Path = CASES,
                                       history_csv: Path = HISTORY) -> dict:
    """Build reusable proof-oriented mock figures and a provenance manifest."""
    target = Path(output_dir)
    if target.exists():
        raise FileExistsError('output_directory_already_exists')
    docs = []
    input_hashes = {}
    for label, name in FIXTURES:
        obj = fixture_dir / name
        meta = obj.with_suffix('.json')
        doc = import_obj(obj, sidecar_path=meta)
        if not doc.synthetic or doc.source_kind != 'synthetic_sidecar':
            raise ValueError('real_or_unqualified_gallery_source')
        if not doc.faces or not set(face.element_type for face in doc.faces) <= {'quad','triangle'}:
            raise ValueError('unexpected_gallery_inventory')
        docs.append(doc)
        input_hashes[name] = doc.source_sha256
        input_hashes[meta.name] = _sha(meta)
    if not (docs[0].triangles == 8 and docs[0].quads == 0
            and docs[1].quads == 1 and docs[1].triangles == 8
            and docs[2].quads == 4 and docs[2].triangles == 0):
        raise ValueError('gallery_fixture_mismatch')
    events, history_hash = load_synthetic_history(history_csv)
    summary = summarize_synthetic_history(events, history_hash)
    if len(events) != 8 or len(summary['groups']) != 2:
        raise ValueError('unexpected_synthetic_history_inventory')
    # Verify exact original source P1 even though it is excluded from mock charts.
    original_obj = import_obj(REAL_P1, auto_sidecar=False)
    original_report = json.loads((REAL_P1.parent / 'generator_report.json').read_text(encoding='utf-8'))
    p1_proof = qualify_p1(original_obj, original_report)
    if original_obj.source_sha256 != SOURCE_OBJ_SHA256 or not p1_proof['source']:
        raise ValueError('unqualified_source_P1')
    target.mkdir(parents=True)
    _topology_gallery(docs, target / 'topology_gallery')
    _synthetic_timeline(events, target / 'epoch_timeline')
    audits = {}
    for file in ('topology_gallery','epoch_timeline'):
        audits[file] = {
            'svg': _scan_svg(target / (file+'.svg')),
            'pdf': _scan_pdf(target / (file+'.pdf'), FIG_W_MM, FIG_H_MM, min_drawings=20),
        }
    with (target/'topology_inventory.csv').open('x', newline='', encoding='utf-8') as stream:
        writer = csv.writer(stream, lineterminator='\n')
        writer.writerow(('fixture', 'source_sha256', 'synthetic', 'triangles', 'quads'))
        for doc, (_,name) in zip(docs,FIXTURES):
            writer.writerow((name,doc.source_sha256,'true',doc.triangles,doc.quads))
    with (target/'epoch_events.csv').open('x',newline='',encoding='utf-8') as stream:
        writer = csv.writer(stream,lineterminator='\n')
        writer.writerow(('dataset','method','epoch','status','normalized_error','elements','wall_seconds','synthetic'))
        for e in events:
            writer.writerow((e.dataset,e.method,e.epoch,
                             'accepted' if e.accepted else 'rejected',
                             format(e.normalized_error,'.17g'),e.elements,
                             format(e.wall_seconds,'.17g'),'true'))
    _json(target/'history_summary.json',summary)
    _json(target/'study_matrix.json',controlled_p1_registry(original_obj.source_sha256))
    recipe = {
        'schema':'apmesh.meshstudio.synthetic_comparison_recipe.v1',
        'evidence_kind':'SYNTHETIC_TEST_DATA_NOT_MEASURED',
        'source_input_hashes':input_hashes,
        'history_csv_sha256':history_hash,
        'figure_dimensions_mm':[FIG_W_MM,FIG_H_MM],
        'figure_panels':{'topology':['tri','quad_tri','all_quad'],
                         'history':['error_vs_elements','seconds_vs_epoch']},
        'source_P1_outside_comparison_matrix':True,
        'source_P1_sha256':original_obj.source_sha256,
        'all_real_adaptive_study_cells':'NOT_AVAILABLE',
        'not_comparable_across_methods':True,
        'camera_policy':'PER_PANEL_INDEPENDENT_FIT_NOT_MATCHED_PHYSICAL_VIEW',
        'metric_claims':'NONE_FROM_ACTUAL_SOURCE',
        'rejected_epoch_policy':'MARKER_ONLY_NOT_ACCEPTED_SERIES',
        'output':'TRUE_VECTOR_2D_SVG_PDF',
    }
    _json(target/'figure.recipe.json',recipe)
    (target/'include.tex').write_text(
        r'\begin{figure*}[tb]'+'\n'+r'  \centering'+'\n'+
        r'  \includegraphics[width=.97\textwidth]{topology_gallery.pdf}'+'\n'+
        r'  \caption{Synthetic topology examples for software validation only. No measured comparison of APMesh methods is implied.}'+'\n'+
        r'  \label{fig:apmesh-synthetic-topologies}'+'\n'+
        r'\end{figure*}'+'\n'+
        r'\begin{figure*}[tb]'+'\n'+r'  \centering'+'\n'+
        r'  \includegraphics[width=.97\textwidth]{epoch_timeline.pdf}'+'\n'+
        r'  \caption{Illustrative synthetic histories; crosses mark rejected candidates. These are not experimental APMesh measurements.}'+'\n'+
        r'  \label{fig:apmesh-synthetic-histories}'+'\n'+
        r'\end{figure*}'+'\n',encoding='utf-8',newline='\n')
    receipt = {
        'schema':'apmesh.meshstudio.synthetic_comparison_receipt.v1',
        'evidence_kind':'SYNTHETIC_TEST_DATA_NOT_MEASURED',
        'figure_audits':audits,
        'source_hashes':input_hashes,
        'history_csv_sha256':history_hash,
        'mock_event_count':len(events),
        'synthetic_only':True,
        'real_source_study_comparison_qualified':False,
        'files_sha256':{p.name:_sha(p) for p in sorted(target.iterdir()) if p.is_file()},
    }
    _json(target/'publication.audit.json',receipt)
    return receipt
