import { expect, test } from '@playwright/test';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const EXPECTED_LEGACY_BLOB_SHA1 = '8f54a95e0192e9af3e76ba5d9f28202cd47dae79';
const EXPECTED_TRIANGLES = 7184;
const EXPECTED_VERTICES = 3691;

// The legacy ap_mesh OBJ is not in the certified Mesh Studio source catalog.
// Its OBJ face order is NOT evidence of the generator's canonical face IDs.
test('R2.7.6 larger legacy ap_mesh OBJ stays unqualified and synchronous index refuses oversize input',
  async ({page}, info) => {
    test.setTimeout(100_000);
    const source = await readFile('../../../reference/eistute_stage4.obj');
    const blobHash = createHash('sha1').update('blob '+source.byteLength+'\0')
      .update(source).digest('hex');
    expect(blobHash).toBe(EXPECTED_LEGACY_BLOB_SHA1);
    const sha256 = createHash('sha256').update(source).digest('hex');
    const vertices:number[] = [], cells:number[][]=[];
    const text = source.toString('utf8');
    expect(text.startsWith('# Wavefront OBJ generated by ap_mesh\n# step 4\n')).toBe(true);
    for (const line of text.split(/\r?\n/)) {
      if (line.startsWith('v ')) {
        const parts=line.trim().split(/\s+/).slice(1);
        expect(parts).toHaveLength(3);
        const xyz=parts.map(Number);
        expect(xyz.every(Number.isFinite)).toBe(true);
        vertices.push(...xyz);
      } else if (line.startsWith('f ')) {
        const words=line.trim().split(/\s+/).slice(1);
        expect(words).toHaveLength(3);
        const ids=words.map(w=>Number(w.split('/')[0])-1);
        expect(ids.every(v=>Number.isSafeInteger(v)&&v>=0)).toBe(true);
        cells.push(ids);
      }
    }
    expect(vertices.length/3).toBe(EXPECTED_VERTICES);
    expect(cells.length).toBe(EXPECTED_TRIANGLES);
    expect(cells.every(c=>c.every(id=>id<EXPECTED_VERTICES)&&new Set(c).size===3)).toBe(true);

    const packed = {
      vertices,
      offsets: cells.map((_,i)=>i*4).concat(cells.length*4),
      polys: cells.flatMap(c=>[3,...c]),
      arities: Array(cells.length).fill(3),
      // IDs are file-local record ordinals only, NEVER scientific APMesh source IDs.
      faceIds: cells.map((_,i)=>i),
    };
    await page.goto('/bench.html');
    const result = await page.evaluate(async ({packed,sha256})=>{
      const {createBoundedXyzBvhMain, MAIN_BVH_MAX_FACES} =
        await import('/src/xyzBvhMain.ts');
      const {createXyzBvhWorker} = await import('/src/xyzBvhClient.ts');
      const view = {
        schema:'apmesh.meshstudio.legacy_reference_probe.v1',
        source_sha256:sha256,
        source_patch_ownership:'UNKNOWN_LEGACY_OBJ_FACE_RECORD_ORDINAL_ONLY',
        coordinate_space:'xyz' as const,
        points:[],cells:[],source_face_ids:[],cell_types:[],
        triangles:packed.faceIds.length,quads:0,
        warning:'UNQUALIFIED_LEGACY_APMESH_GENERATOR_STEP4_OBJ_NOT_CERTIFIED_SOURCE',
        packed:{
          vertices:new Float32Array(packed.vertices),
          offsets:new Uint32Array(packed.offsets),
          polys:new Uint32Array(packed.polys),
          arities:new Uint8Array(packed.arities),
          faceIds:new Uint32Array(packed.faceIds),
        },
      };
      const originalIds=view.packed.faceIds.slice();
      const originalPositions=view.packed.vertices.slice();
      const syncStart=performance.now();
      const sync=createBoundedXyzBvhMain(view);
      const syncCheckMs=performance.now()-syncStart;
      const client=createXyzBvhWorker(view);
      if(!client)throw new Error('large_reference_worker_client_not_initialized');
      try {
        const workerQualified=await client.ready;
        const coverage=client.coverage();
        const profile=client.buildMeasurement();
        const selected=[];
        if (workerQualified) {
          const count=15;
          for(let sample=0;sample<count;sample++){
            const f=Math.floor(sample*packed.faceIds.length/count);
            const at=packed.offsets[f];
            const atVertex=(corner:number):[number,number,number]=>{
              const i=packed.polys[at+corner+1]*3;
              return [view.packed.vertices[i],view.packed.vertices[i+1],view.packed.vertices[i+2]];
            };
            const [a,b,c]=[atVertex(0),atVertex(1),atVertex(2)];
            const center=a.map((v,i)=>(v+b[i]+c[i])/3);
            const u=b.map((v,i)=>v-a[i]),v=c.map((x,i)=>x-a[i]);
            const n=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]];
            const norm=Math.hypot(...n);
            if(norm<1e-12){selected.push({kind:'degenerate',ordinal:f});continue;}
            const near=center.map((x,i)=>x+.001*n[i]/norm) as [number,number,number];
            const far=center.map((x,i)=>x-.001*n[i]/norm) as [number,number,number];
            const r=await client.pickWithMeasurement(near,far,true,false);
            selected.push({
              ordinal:f,kind:r.outcome.kind,
              selectedOrdinal:r.outcome.kind==='hit'?r.outcome.sourceFaceId:null,
              tested:r.outcome.testedFaces,
              workerCpuMs:r.workerQueryWallMs,roundTripMs:r.roundTripWallMs,
              status:r.status,
            });
          }
        }
        return {
          sourceSha256:view.source_sha256,
          synchronousRejected:sync===null,
          synchronousFaceLimit:MAIN_BVH_MAX_FACES,
          syncCheckMs,workerQualified,coverage,profile,
          copiedInputBytes:view.packed.vertices.byteLength+view.packed.offsets.byteLength+
            view.packed.polys.byteLength+view.packed.arities.byteLength+
            view.packed.faceIds.byteLength,
          buffersIntact:originalIds.every((id,i)=>id===view.packed.faceIds[i]) &&
            originalPositions.every((x,i)=>x===view.packed.vertices[i]),
          selections:selected,
        };
      }finally{client.dispose();}
    },{packed,sha256});
    expect(result.sourceSha256).toBe(sha256);
    expect(result.synchronousFaceLimit).toBe(2048);
    expect(result.synchronousRejected).toBe(true);
    expect(result.buffersIntact).toBe(true);
    expect(result.copiedInputBytes).toBeGreaterThan(150_000);
    if(result.workerQualified) {
      expect(result.coverage).toEqual({
        sourceFaces:EXPECTED_TRIANGLES,indexedFaces:EXPECTED_TRIANGLES,excludedQuadFaces:0,
      });
      for(const row of result.selections) {
        if(row.kind==='hit')expect(row.selectedOrdinal).toBe(row.ordinal);
      }
    }
    const receipt={
      schema:'apmesh.meshstudio.r276.legacy_large_obj_preflight.v1',
      originalRepositoryPath:'reference/eistute_stage4.obj',
      originalGitBlobSha1:blobHash,originalBytes:source.byteLength,originalSha256:sha256,
      objHeader:'Wavefront OBJ generated by ap_mesh / step 4',
      vertices:EXPECTED_VERTICES,triangles:EXPECTED_TRIANGLES,quads:0,
      sourceStatus:'LEGACY_REPOSITORY_REFERENCE_NOT_SCIENTIFICALLY_QUALIFIED',
      faceIds:'OBJ_RECORD_ORDINAL_NOT_GENERATOR_CERTIFIED_SOURCE_ID',
      patchOwnership:'UNKNOWN_FROM_OBJ',
      acceptedAdaptiveEpochs:'UNVERIFIED',
      input:result,
      warnings:[
        'never_merge_this_model_into_scientifically_qualified_P1_catalog_without_lineage',
        'no_independent_generator_report_UV_patch_curve_or_adaptation_epoch_evidence',
        'worker_index_eligibility_is_not_scientific_equivalence',
        'the_prototype_main_thread_cap_refuses_7184_face_input_by_design',
        'memory_is_typed_array_input_only_not_full_RSS_heap_or_GPU_VRAM',
        'only_15_local_ray_samples_and_not_a_qualified_viewport_AB_C',
      ],
    };
    const json=JSON.stringify(receipt,null,2)+'\n';
    await mkdir('test-results',{recursive:true});
    await writeFile('test-results/r276-legacy-large-obj-preflight.json',json,'utf8');
    await info.attach('r276-legacy-large-obj-preflight.json',{
      body:Buffer.from(json),contentType:'application/json',
    });
    console.log('R276_LEGACY_LARGE_OBJ='+JSON.stringify({
      sha256,blobHash,vertices:EXPECTED_VERTICES,triangles:EXPECTED_TRIANGLES,
      syncRefused:result.synchronousRejected,workerQualified:result.workerQualified,
      nodeCount:result.profile?.nodeCount,workerBuildMs:result.profile?.workerBuildWallMs,
      workerReadyMs:result.profile?.readyRoundTripMs,copiedInputBytes:result.copiedInputBytes,
      hitRecordOrdinals:result.selections.filter(s=>s.kind==='hit').length,
      status:'UNQUALIFIED_LEGACY_REFERENCE_ONLY',
    }));
  });
