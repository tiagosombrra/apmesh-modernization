"""Deterministic raster-free SVG renderer for explicitly sourced UV mesh faces."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

from .model import MeshDocument

URI = "http://www.w3.org/2000/svg"
ET.register_namespace("", URI)


def _tag(name):
    return f"{{{URI}}}{name}"


def render_uv_svg(document: MeshDocument, output: Path | str,
                  *, width_mm: float = 155.0, height_mm: float = 120.0) -> dict:
    """Draw source UV, never silently substitute XY-projected XYZ coordinates."""
    if not document.faces or any(face.uv is None for face in document.faces):
        raise ValueError("uv_required_for_vector_figure")
    if not (25 <= width_mm <= 400 and 25 <= height_mm <= 400):
        raise ValueError("invalid_figure_size")
    all_uv = [point for face in document.faces for point in face.uv]
    min_x = min(p[0] for p in all_uv)
    max_x = max(p[0] for p in all_uv)
    min_y = min(p[1] for p in all_uv)
    max_y = max(p[1] for p in all_uv)
    if max_x <= min_x or max_y <= min_y:
        raise ValueError("invalid_uv_extent")
    width, height = 900, 700
    left, right, top, bottom = 74, 70, 70, 100
    viewport_w = width - left - right
    viewport_h = height - top - bottom
    scale = min(viewport_w / (max_x - min_x), viewport_h / (max_y - min_y))
    offset_x = left + (viewport_w - scale * (max_x - min_x)) / 2
    offset_y = top + (viewport_h - scale * (max_y - min_y)) / 2

    def point_xy(p):
        return (offset_x + scale * (p[0] - min_x),
                height - bottom - (offset_y - top) - scale * (p[1] - min_y))

    root = ET.Element(_tag("svg"), {
        "width": f"{width_mm:g}mm", "height": f"{height_mm:g}mm",
        "viewBox": f"0 0 {width} {height}", "version": "1.1", "role": "img",
        "aria-label": "Source UV mesh figure, generated by APMesh Mesh Studio",
    })
    ET.SubElement(root, _tag("title")).text = "APMesh Mesh Studio — UV mesh"
    ET.SubElement(root, _tag("desc")).text = (
        "This figure is synthetic and not a measured APMesh scientific result."
        if document.synthetic else "Source geometry from an imported mesh; metrics not inferred.")
    ET.SubElement(root, _tag("rect"), {"width": str(width), "height": str(height),
                                        "fill": "#ffffff"})
    face_group = ET.SubElement(root, _tag("g"), {"stroke": "#203246", "stroke-width": "2.25",
                                                    "stroke-linejoin": "round"})
    colors = {"triangle": "#e7edf5", "quad": "#8dc8c6"}
    for face in document.faces:
        coords = " ".join(f"{x:.4f},{y:.4f}" for x, y in map(point_xy, face.uv))
        ET.SubElement(face_group, _tag("polygon"), {
            "points": coords, "fill": colors[face.element_type],
            "data-cell-type": face.element_type, "data-source-group": face.group,
        })
    ET.SubElement(root, _tag("text"), {"x": "60", "y": "40", "fill": "#182335",
                                           "font-size": "27", "font-family": "sans-serif",
                                           "font-weight": "bold"}).text = "Parametric mesh (UV)"
    caption = f"{document.quads} QUAD  |  {document.triangles} TRI  |  {len(document.points)} vertices"
    ET.SubElement(root, _tag("text"), {"x": "60", "y": "655", "fill": "#354355",
                                           "font-size": "19", "font-family": "sans-serif"}).text = caption
    if document.synthetic:
        ET.SubElement(root, _tag("text"), {"x": "60", "y": "684", "fill": "#9f352b",
                                               "font-size": "18", "font-weight": "bold",
                                               "font-family": "sans-serif"}).text = "SYNTHETIC — NOT A SCIENTIFIC RESULT"
    else:
        ET.SubElement(root, _tag("text"), {"x": "60", "y": "684", "fill": "#354355",
                                               "font-size": "15", "font-family": "sans-serif"}).text = "Imported source mesh; not a quality certificate"
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(root).write(output, encoding="utf-8", xml_declaration=True)
    return {
        "schema": "apmesh.meshstudio.vector_figure.v1",
        "format": "svg", "render_class": "source_uv_vector_2d",
        "synthetic": document.synthetic, "source_kind": document.source_kind,
        "source_obj_sha256": document.source_sha256,
        "semantic_sidecar_sha256": document.semantic_sidecar_sha256,
        "triangle_count": document.triangles, "quad_count": document.quads,
        "vertex_count": len(document.points), "width_mm": width_mm,
        "height_mm": height_mm, "svg_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
    }


def audit_svg(path: Path | str, expected_faces: int | None = None) -> dict:
    """Reject raster payloads and external resources in publication SVG output."""
    path = Path(path)
    root = ET.fromstring(path.read_bytes())
    if root.tag != _tag("svg"):
        raise ValueError("not_svg")
    forbidden = {"image", "foreignObject", "script", "use", "filter", "feImage"}
    count = 0
    for element in root.iter():
        local = element.tag.split("}")[-1]
        if local in forbidden:
            raise ValueError("non_vector_or_active_svg_content")
        for attr, value in element.attrib.items():
            if attr.endswith("href") or attr.startswith("on") or "url(" in value:
                raise ValueError("external_svg_dependency")
        if local == "polygon":
            count += 1
    if expected_faces is not None and expected_faces != count:
        raise ValueError("figure_cell_count_mismatch")
    return {"vector_only": True, "raster_image_count": 0, "polygon_count": count}


def save_receipt(receipt: dict, path: Path | str) -> None:
    Path(path).write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n", encoding="utf-8")
